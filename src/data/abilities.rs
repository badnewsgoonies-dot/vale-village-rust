// ---------------------------------------------------------------------------
// Ability type system
// ---------------------------------------------------------------------------

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum AbilityType {
    Physical,
    Psynergy,
    Healing,
    Buff,
    Debuff,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum TargetKind {
    SingleEnemy,
    AllEnemies,
    SingleAlly,
    AllAllies,
    #[serde(rename = "self")]
    OneSelf,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum AiTargetPref {
    Weakest,
    LowestRes,
    HighestDef,
    HealerFirst,
    Random,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AiHints {
    pub priority: f32,
    pub target: AiTargetPref,
    #[serde(default)]
    pub avoid_overkill: bool,
    #[serde(default)]
    pub opener: bool,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BuffEffect {
    #[serde(default)]
    pub atk: i32,
    #[serde(default)]
    pub def: i32,
    #[serde(default)]
    pub mag: i32,
    #[serde(default)]
    pub spd: i32,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct StatusEffectDef {
    pub effect_type: String, // "poison", "burn", "freeze", "paralyze"
    pub duration: u8,
    #[serde(default)]
    pub chance: f32,
}

// ---------------------------------------------------------------------------
// Core ability definition
// ---------------------------------------------------------------------------

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Ability {
    pub id: String,
    pub name: String,
    pub ability_type: AbilityType,
    #[serde(default)]
    pub element: Option<Element>,
    pub mana_cost: i32,
    pub base_power: i32,
    pub targets: TargetKind,
    pub unlock_level: u8,
    pub description: String,
    #[serde(default)]
    pub buff_effect: Option<BuffEffect>,
    #[serde(default)]
    pub duration: Option<u8>,
    #[serde(default)]
    pub status_effect: Option<StatusEffectDef>,
    #[serde(default)]
    pub chain_damage: bool,
    #[serde(default)]
    pub ignore_defense_percent: f32,
    #[serde(default)]
    pub damage_reduction_percent: f32,
    #[serde(default)]
    pub shield_charges: Option<u8>,
    pub ai_hints: AiHints,
}

